use anyhow::{Result, ensure};

pub fn urlencode(s: &str) -> String {
    s.bytes()
        .map(|b| match b {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => {
                (b as char).to_string()
            }
            _ => format!("%{b:02X}"),
        })
        .collect()
}

/// 今日の日付を `YYYY-MM-DD`（UTC）で返す。
/// 環境変数 `BUILD_DATE` があればそれを使う。
pub fn today_iso() -> Result<String> {
    today_or(std::env::var("BUILD_DATE").ok().as_deref())
}

pub fn today_or(date_override: Option<&str>) -> Result<String> {
    if let Some(date) = date_override {
        ensure!(
            is_iso_date(date),
            "BUILD_DATE は YYYY-MM-DD で指定してください: {date}"
        );
        return Ok(date.to_string());
    }
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0);
    let (y, m, d) = civil_from_days(secs.div_euclid(86_400));
    Ok(format!("{y:04}-{m:02}-{d:02}"))
}

pub fn is_iso_date(s: &str) -> bool {
    let b = s.as_bytes();
    b.len() == 10
        && b.iter().enumerate().all(|(i, c)| {
            if i == 4 || i == 7 {
                *c == b'-'
            } else {
                c.is_ascii_digit()
            }
        })
}

/// 1970-01-01 からの経過日数を (年, 月, 日) に変換する（Howard Hinnant の civil_from_days）
pub fn civil_from_days(days: i64) -> (i64, i64, i64) {
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = yoe + era * 400 + i64::from(m <= 2);
    (y, m, d)
}
